import { describe, expect, it } from 'vitest'

import type { DomainEnvelopeEvidenceAnchorProjection, EvidenceRecord } from '../types'
import {
  buildNavigationCommandFromChatEvidenceRecord,
  buildNavigationCommandFromEnvelopeEvidenceProjection,
} from './navigationSourceAdapters'
import { evidenceViewerSearchText, tableRowSearchText } from './tableRowSearchText'

// Made-up rows in the exact stored form of a whole-row table piece (P3/P4).
const SHORT_ROW = '| XS1 | 3 | 5 | 4.0 |'
const LONG_ROW =
  '| XS0404 | ced-3(n717) IV; zeta-3(tm999) III; ccIs4251 [myo-3p::GFP] | 25 C | This study, generated by CRISPR |'

describe('tableRowSearchText', () => {
  it('turns a stored table row into the text a PDF shows for it', () => {
    expect(tableRowSearchText(SHORT_ROW)).toBe('XS1 3 5 4.0')
    expect(tableRowSearchText(LONG_ROW)).toBe(
      'XS0404 ced-3(n717) IV; zeta-3(tm999) III; ccIs4251 [myo-3p::GFP] 25 C This study, generated by CRISPR',
    )
  })

  it('keeps escaped pipes as text, skips empty cells and collapses nothing else', () => {
    expect(tableRowSearchText('| a \\| b |  | c |')).toBe('a | b c')
  })

  it('applies only to table-row fragments, joined like the verified quote', () => {
    expect(evidenceViewerSearchText([{ text: 'A sentence.', span_type: 'sentence' }])).toBeNull()
    expect(evidenceViewerSearchText(undefined)).toBeNull()
    expect(evidenceViewerSearchText([
      { text: 'Strains are listed below.', span_type: 'sentence' },
      { text: SHORT_ROW, span_type: 'table_row' },
    ])).toBe('Strains are listed below.\n\nXS1 3 5 4.0')
  })
})

function chatRecord(overrides: Partial<EvidenceRecord> = {}): EvidenceRecord {
  return {
    entity: 'zeta',
    verified_quote: SHORT_ROW,
    page: 4,
    section: 'Results',
    chunk_id: 'chunk-4',
    source_fragments: [{ text: SHORT_ROW, span_type: 'table_row', span_id: 'chunk-4:s0003:c0010-c0031:abcdef12' }],
    ...overrides,
  }
}

describe('evidence navigation for table-row quotes', () => {
  it('searches a chat table-row quote by its cell text and keeps the exact quote for display', () => {
    const command = buildNavigationCommandFromChatEvidenceRecord(chatRecord())
    expect(command.searchText).toBe('XS1 3 5 4.0')
    expect(command.anchor.viewer_search_text).toBe('XS1 3 5 4.0')
    expect(command.anchor.snippet_text).toBe(SHORT_ROW)
  })

  it('leaves a prose quote unchanged', () => {
    const command = buildNavigationCommandFromChatEvidenceRecord(chatRecord({
      verified_quote: 'A prose sentence.',
      source_fragments: [{ text: 'A prose sentence.', span_type: 'sentence' }],
    }))
    expect(command.searchText).toBe('A prose sentence.')
  })

  it('searches a review-grid table-row quote by its cell text, read from the source record', () => {
    const projection = {
      anchor_id: 'projection-1',
      evidence_record_id: 'evidence-1',
      envelope_id: 'envelope-1',
      object_id: 'object-1',
      envelope_revision: 1,
      quote: LONG_ROW,
      page_number: 2,
      chunk_ids: ['chunk-2'],
      anchor: {
        anchor_kind: 'snippet',
        locator_quality: 'exact_quote',
        supports_decision: 'supports',
        snippet_text: LONG_ROW,
        sentence_text: LONG_ROW,
        viewer_search_text: LONG_ROW,
        page_number: 2,
        chunk_ids: ['chunk-2'],
      },
      metadata: {
        source_record: { verified_quote: LONG_ROW, source_fragments: [{ text: LONG_ROW, span_type: 'table_row' }] },
      },
    } as DomainEnvelopeEvidenceAnchorProjection

    const command = buildNavigationCommandFromEnvelopeEvidenceProjection(projection)
    expect(command?.searchText).toBe(tableRowSearchText(LONG_ROW))
    expect(command?.anchor.snippet_text).toBe(LONG_ROW)
  })
})
