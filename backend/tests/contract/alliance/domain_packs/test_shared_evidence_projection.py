"""All seven packs share one evidence projection but keep their own policy.

KANBAN-1773. The seven `allowed_fields = set(EvidenceRecord.model_fields)` loops
were replaced by `normalize_workspace_records`. Two packs were never identical
to the other five, and flattening them would have changed behavior silently:

- GO drops evidence with no verified quote.
- gene_expression reports each dropped record.

One test file for all seven, rather than seven copies of the same test.
"""

