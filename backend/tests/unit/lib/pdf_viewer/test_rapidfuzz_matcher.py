"""Unit tests for RapidFuzz PDF evidence localization."""

import pytest

from src.lib.pdf_viewer.rapidfuzz_matcher import MIN_FUZZY_MATCH_SCORE, PdfPageText, match_quote_to_pdf_pages


def test_match_quote_to_pdf_pages_localizes_single_page_quote():
    result = match_quote_to_pdf_pages(
        "Perturbing Crb affects rhabdomere morphogenesis and eventually leads to retinal degeneration.",
        [
            PdfPageText(page_number=1, raw_text="Introduction and background."),
            PdfPageText(
                page_number=2,
                raw_text=(
                    "Results. Perturbing Crb affects rhabdomere morphogenesis and, eventually, "
                    "leads to retinal degeneration. However, how the rhabdomere proteins change remains unclear."
                ),
            ),
            PdfPageText(page_number=3, raw_text="Discussion."),
        ],
    )

    assert result.found is True
    assert result.strategy == "rapidfuzz-single-page"
    assert result.matched_page == 2
    assert result.matched_range is not None
    assert "Perturbing Crb affects rhabdomere morphogenesis" in (result.matched_query or "")
    assert result.cross_page is False


def test_match_quote_to_pdf_pages_uses_page_hints_as_tie_breaker():
    duplicated_quote = "The same evidence sentence appears in multiple places."

    result = match_quote_to_pdf_pages(
        duplicated_quote,
        [
            PdfPageText(page_number=2, raw_text=f"Results. {duplicated_quote} More text."),
            PdfPageText(page_number=3, raw_text=f"Methods. {duplicated_quote} More text."),
        ],
        page_hints=[3],
    )

    assert result.found is True
    assert result.matched_page == 3
    assert result.matched_range is not None
    assert result.matched_range.page_number == 3


def test_match_quote_to_pdf_pages_supports_cross_page_spans():
    result = match_quote_to_pdf_pages(
        "all proteins changed in the allele lacking the crb_C isoform constitute interesting candidates in the connection of the Crumbs function in organizing the cytoskeleton",
        [
            PdfPageText(page_number=1, raw_text="Introduction"),
            PdfPageText(
                page_number=2,
                raw_text="Results. all proteins changed in the allele lacking the crb_C isoform constitute interesting candidates",
            ),
            PdfPageText(
                page_number=3,
                raw_text="in the connection of the Crumbs function in organizing the cytoskeleton and should be prioritized.",
            ),
        ],
        page_hints=[2],
    )

    assert result.found is True
    assert result.cross_page is True
    assert result.matched_page == 2
    assert len(result.page_ranges) == 2
    assert result.page_ranges[0].page_number == 2
    assert result.page_ranges[1].page_number == 3


def test_match_quote_to_pdf_pages_rejects_low_scoring_candidates():
    result = match_quote_to_pdf_pages(
        "completely unrelated quote text",
        [
            PdfPageText(page_number=1, raw_text="Introduction and background"),
            PdfPageText(page_number=2, raw_text="Methods and materials"),
        ],
        min_score=99.0,
    )

    assert result.found is False
    assert result.matched_page is not None
    assert result.score < 99.0


# --- Table-row quotes (P4 follow-up) ---------------------------------------------------
# A table-row quote is stored as Markdown with pipes; a PDF's text layer has none. The
# viewer therefore sends the row's cell text for table-row evidence (frontend
# ``tableRowSearchText``). These pin why: the pipe form of a short row falls below the
# match threshold, while its cell text matches exactly. Made-up rows.

_TABLE_PAGE = PdfPageText(
    page_number=4,
    raw_text=(
        "Table S3. Counts per replicate\nLine Rep 1 Rep 2 Mean\nN2 12 14 13.0\n"
        "XS1 3 5 4.0\nXS2 0 1 0.5\nXS3 7 9 8.0\n"
        "XS0404 ced-3(n717) IV; zeta-3(tm999) III; ccIs4251 [myo-3p::GFP] 25 C This study, generated by CRISPR\n"
    ),
)
_OTHER_PAGE = PdfPageText(page_number=1, raw_text="Methods. Worms were grown on NGM plates at 20 C.")


@pytest.mark.parametrize(
    "pipe_quote,cell_text",
    [
        ("| XS1 | 3 | 5 | 4.0 |", "XS1 3 5 4.0"),
        ("| XS2 | 0 | 1 | 0.5 |", "XS2 0 1 0.5"),
    ],
    ids=["short-row-1", "short-row-2"],
)
def test_a_short_table_row_matches_only_by_its_cell_text(pipe_quote, cell_text):
    pages = [_OTHER_PAGE, _TABLE_PAGE]

    with_pipes = match_quote_to_pdf_pages(pipe_quote, pages)
    by_cells = match_quote_to_pdf_pages(cell_text, pages)

    assert with_pipes.found is False
    assert with_pipes.score < MIN_FUZZY_MATCH_SCORE
    assert by_cells.found is True
    assert by_cells.score == 100.0
    assert by_cells.matched_page == 4
    assert by_cells.matched_query == cell_text


def test_a_long_table_row_matches_better_by_its_cell_text():
    pipe_quote = (
        "| XS0404 | ced-3(n717) IV; zeta-3(tm999) III; ccIs4251 [myo-3p::GFP] | 25 C | This study, generated by CRISPR |"
    )
    cell_text = "XS0404 ced-3(n717) IV; zeta-3(tm999) III; ccIs4251 [myo-3p::GFP] 25 C This study, generated by CRISPR"

    with_pipes = match_quote_to_pdf_pages(pipe_quote, [_OTHER_PAGE, _TABLE_PAGE])
    by_cells = match_quote_to_pdf_pages(cell_text, [_OTHER_PAGE, _TABLE_PAGE])

    assert with_pipes.found is True and with_pipes.score < 100.0
    assert by_cells.found is True and by_cells.score == 100.0
