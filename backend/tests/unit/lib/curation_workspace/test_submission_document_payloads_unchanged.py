def _snapshot_ids(value) -> set[str]:
    """Validation snapshot ids generated by the database at preview time (random)."""

    if isinstance(value, dict):
        found = {value["snapshot_id"]} if isinstance(value.get("snapshot_id"), str) else set()
        for item in value.values():
            found |= _snapshot_ids(item)
        return found
    if isinstance(value, list):
        return set().union(*(_snapshot_ids(item) for item in value)) if value else set()
    return set()


def _without_snapshot_ids(text: str, snapshot_ids: set[str]) -> str:
    for snapshot_id in snapshot_ids:
        text = text.replace(snapshot_id, "SNAPSHOT-ID")
    return text


def _digest(value) -> str:
    text = value if isinstance(value, str) else json.dumps(value, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


class _FixedClock(datetime):
    @classmethod
    def now(cls, tz=None):
        return datetime(2026, 11, 22, 12, 0, tzinfo=timezone.utc)


@pytest.fixture
def fixed_ids(monkeypatch):
    """Same ids and clock on every run, so digests compare across code versions."""

    counter = iter(range(1, 10_000))
    def fixed_uuid4():
        return uuid_module.UUID(int=next(counter))

    for seeded_module in (seeds, submission_module, validation_module):
        monkeypatch.setattr(seeded_module, "uuid4", fixed_uuid4)
    monkeypatch.setattr(submission_module, "datetime", _FixedClock)
    monkeypatch.setattr(validation_module, "datetime", _FixedClock)


def _digests(db) -> dict[str, str]:
    seeded = seeds._create_decision_session(
        db, first_candidate_status=CurationCandidateStatus.ACCEPTED
    )
    session_row = db.get(ReviewSessionModel, uuid_module.UUID(seeded["session_id"]))
    candidate = db.get(CurationCandidate, uuid_module.UUID(seeded["first_candidate_id"]))

    fingerprint = submission_module._submission_intent_fingerprint(
        db=db,
        session_row=session_row,
        adapter_key=session_row.adapter_key,
        mode=SubmissionMode.EXPORT,
        target_key=_EXPORT_TARGET,
        ready_candidates=[candidate],
        domain_context=None,
    )
    persisted = submission_module._base_submission_payload_context(
        db=db,
        session_row=session_row,
        ready_candidates=[candidate],
        session_validation=None,
    )
    preview = module.submission_preview(
        db,
        seeded["session_id"],
        CurationSubmissionPreviewRequest(
            session_id=seeded["session_id"],
            mode=SubmissionMode.EXPORT,
            target_key=_EXPORT_TARGET,
        ),
    )
    payload = preview.submission.payload
    assert persisted["document"] is not None
    assert payload is not None and payload.payload_json is not None and payload.payload_text
    snapshot_ids = _snapshot_ids(payload.payload_json)
    export_json = _without_snapshot_ids(
        json.dumps(payload.payload_json, sort_keys=True, separators=(",", ":")), snapshot_ids
    )
    return {
        "intent_fingerprint": _digest(fingerprint),
        "persisted_document": _digest(persisted["document"]),
        "export_payload_json": _digest(export_json),
        "export_payload_text": _digest(_without_snapshot_ids(payload.payload_text, snapshot_ids)),
    }


def test_submission_fingerprint_persisted_document_and_export_match_main(request, fixed_ids):
    actual = _digests(request.getfixturevalue("db_session"))

    assert actual == EXPECTED_DIGESTS
