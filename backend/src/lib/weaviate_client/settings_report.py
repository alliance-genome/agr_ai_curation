"""Read-only report: a search index server's engine version and how its stored
collection settings differ from what current code creates.

Prints setting names and counts only: no objects, no tenants, no values beyond
configuration names. Run inside the backend container:

    python -m src.lib.weaviate_client.settings_report

It reads ``WEAVIATE_HOST``, ``WEAVIATE_PORT``, ``WEAVIATE_SCHEME`` and
``WEAVIATE_API_KEY`` like the backend does, takes the embedding model from the
backend's search settings, and only sends GET requests to ``/v1/meta`` and
``/v1/schema``.
"""

from __future__ import annotations

import json
import os
from typing import Any, Dict, Iterable, Optional

import httpx
from weaviate.collections.classes.config import _CollectionConfigCreate

from .collection_definitions import required_collection_definitions

# Weaviate writes this fixed text into the description of every property its
# auto-schema feature created (followed by a timestamp). Matching it is a check
# on a server-generated configuration string, not on paper text.
AUTO_SCHEMA_DESCRIPTION_PREFIX = "This property was generated by Weaviate's auto-schema feature"


def expected_collection_payloads(embedding_model: str) -> Dict[str, Dict[str, Any]]:
    """Render current code's collection definitions as the client would send them."""
    payloads = {}
    for name, kwargs in required_collection_definitions(embedding_model).items():
        payloads[name] = _CollectionConfigCreate(name=name, **kwargs)._to_dict(
            emit_default_vector_index_type=True
        )
    return payloads


def _vectorizer(collection: Dict[str, Any]) -> Optional[str]:
    value = collection.get("vectorizer")
    if value:
        return str(value)
    modules = collection.get("moduleConfig") or {}
    return next(iter(modules), None) or None


def _module_setting(prop: Dict[str, Any], vectorizer: Optional[str], key: str) -> Any:
    if not vectorizer:
        return None
    return ((prop.get("moduleConfig") or {}).get(vectorizer) or {}).get(key)


def _names(values: Iterable[str]) -> list:
    return sorted(values)


def compare_collection(expected: Dict[str, Any], stored: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """Differences for one collection, by setting and property name only."""
    expected_props = {p["name"]: p for p in expected.get("properties") or []}
    if stored is None:
        return {
            "on_server": False,
            "properties_in_code": len(expected_props),
        }
    stored_props = {p["name"]: p for p in stored.get("properties") or []}
    code_vectorizer = _vectorizer(expected)
    server_vectorizer = _vectorizer(stored)
    shared = set(expected_props) & set(stored_props)

    def differs(key: str) -> list:
        return _names(
            name for name in shared
            if _module_setting(expected_props[name], code_vectorizer, key)
            != _module_setting(stored_props[name], server_vectorizer, key)
        )

    code_model = ((expected.get("moduleConfig") or {}).get(code_vectorizer) or {}).get("model")
    server_model = ((stored.get("moduleConfig") or {}).get(server_vectorizer) or {}).get("model")
    return {
        "on_server": True,
        "properties_in_code": len(expected_props),
        "properties_on_server": len(stored_props),
        "properties_missing_on_server": _names(set(expected_props) - set(stored_props)),
        "properties_only_on_server": _names(set(stored_props) - set(expected_props)),
        # Created by the server's auto-schema, even when code declares the same name.
        "properties_auto_created_on_server": _names(
            name for name, prop in stored_props.items()
            if str(prop.get("description") or "").startswith(AUTO_SCHEMA_DESCRIPTION_PREFIX)
        ),
        "data_type_differences": _names(
            name for name in shared
            if expected_props[name].get("dataType") != stored_props[name].get("dataType")
        ),
        "vectorizer_skip_differences": differs("skip"),
        "vectorize_property_name_differences": differs("vectorizePropertyName"),
        "vectorizer": {"code": code_vectorizer, "server": server_vectorizer},
        "embedding_model": {"code": code_model, "server": server_model},
        "multi_tenancy": {
            "code": bool((expected.get("multiTenancyConfig") or {}).get("enabled")),
            "server": bool((stored.get("multiTenancyConfig") or {}).get("enabled")),
        },
        # Server defaults, not set by code: reported as stored, for comparing servers.
        "filter_strategy_stored": (stored.get("vectorIndexConfig") or {}).get("filterStrategy"),
        "deletion_strategy_stored": (stored.get("replicationConfig") or {}).get("deletionStrategy"),
    }


def build_report(meta: Dict[str, Any], schema: Dict[str, Any], embedding_model: str,
                 expected_version: Optional[str]) -> Dict[str, Any]:
    stored = {c["class"]: c for c in schema.get("classes") or []}
    expected = expected_collection_payloads(embedding_model)
    return {
        "engine_version": meta.get("version"),
        "expected_engine_version": expected_version,
        "engine_version_matches": (
            None if expected_version is None else meta.get("version") == expected_version
        ),
        "collections_on_server": len(stored),
        "collections": {
            name: compare_collection(payload, stored.get(name))
            for name, payload in expected.items()
        },
        "collections_only_on_server": _names(set(stored) - set(expected)),
    }


def _server_url() -> str:
    scheme = os.getenv("WEAVIATE_SCHEME", "http")
    host = os.getenv("WEAVIATE_HOST", "localhost")
    port = os.getenv("WEAVIATE_PORT", "8080")
    return f"{scheme}://{host}:{port}"


def main() -> int:
    # The same model backend startup creates collections with (EMBEDDING_MODEL;
    # importing the settings module already requires it).
    from .settings import _current_config

    embedding_model = _current_config["embedding"]["modelName"]
    api_key = os.getenv("WEAVIATE_API_KEY") or None
    headers = {"Authorization": f"Bearer {api_key}"} if api_key else {}
    with httpx.Client(base_url=_server_url(), headers=headers, timeout=30.0) as client:
        meta = client.get("/v1/meta")
        meta.raise_for_status()
        schema = client.get("/v1/schema")
        schema.raise_for_status()
    expected_version = os.getenv("WEAVIATE_EXPECTED_VERSION", "").strip() or None
    report = build_report(meta.json(), schema.json(), embedding_model, expected_version)
    print(json.dumps(report, indent=1, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
